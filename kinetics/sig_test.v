module kinetics

fn test_sig() {
	cases := {
		1.0:           '1'
		-1.0:          '-1'
		123456.0:      '123460'
		1234567.0:     '1.2346e6'
		13155000000.0: '1.3155e10'
		6.0916e9:      '6.0916e9'
		0.00068992:    '0.00068992'
		0.000012345:   '1.2345e-5'
		4312.8:        '4312.8'
		0.5:           '0.5'
		99999.5:       '100000'
		999995.0:      '1e6'
		1e-300:        '1e-300'
		-0.28083:      '-0.28083'
		2.4147e-15:    '2.4147e-15'
		3453.38:       '3453.4'
		900.0:         '900'
		0.1 + 0.2:     '0.3'
		1.0e21:        '1e21'
	}
	for x, want in cases {
		assert sig(x) == want, '${x}: ${sig(x)}'
	}
}
