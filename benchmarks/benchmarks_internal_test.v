module benchmarks

import os

// The harness's own arithmetic and formatting.

fn test_summary_is_the_median_and_minimum() {
	odd := summary([i64(5000), 1000, 3000], Answer{})
	assert odd.median_us == 3.0 && odd.min_us == 1.0 && odd.calls == 3
	even := summary([i64(4000), 1000, 3000, 2000], Answer{})
	assert even.median_us == 2.5 && even.min_us == 1.0
}

fn test_durations_print_in_microseconds_or_milliseconds() {
	assert duration(45.678) == '45.7 µs'
	assert duration(999.4) == '999 µs'
	assert duration(999.6) == '1.00 ms'
	assert duration(40.0) == '40.0 µs'
	assert duration(1234.5) == '1.23 ms'
	assert duration(15678.0) == '15.7 ms'
	assert sig(120.05, 2) == '120'
	assert sig(7.34, 2) == '7.3'
}

fn test_the_report_shows_failures_and_ratios() {
	fx := Fixture{
		states:  1
		systems: [System{
			name:       'methane/n-butane'
			components: [Component{}, Component{}]
		}]
		cases:   [
			Case{
				kind:          'pt2'
				reflux:        Timing{
					median_us: 40.0
					min_us:    30.0
					answer:    Answer{
						beta: 0.2
					}
				}
				thermo:        Timing{
					median_us: 2000.0
					answer:    Answer{
						beta: 0.25
					}
				}
				dwsim_default: Timing{
					error: 'Exception: no convergence'
				}
				dwsim_tight:   Timing{
					median_us: 500.0
					answer:    Answer{
						beta: 0.2
					}
				}
			},
		]
	}
	text := report(fx)
	assert text.contains('| PT, two phases | 2: methane/n-butane | 40.0 µs | 2.00 ms | failed | 500 µs | 50× | – |')
	assert text.contains('| PT, two phases | 2: methane/n-butane | β = 0.2 | 0.05 | – | 0 |')
	assert text.contains('- PT, two phases, 2: methane/n-butane, DWSIM: Exception: no convergence')
	// The minimum's table, with its own ratios: thermo's minimum is unset
	// here, so 0.0 µs and a ratio of 0.
	assert text.contains('| PT, two phases | 2: methane/n-butane | 30.0 µs | 0 µs | failed | 0 µs | 0× | – |')
}

fn test_answers_and_versions_print_plainly() {
	assert decimals(1.0, 8) == '1'
	assert decimals(0.239229746325, 8) == '0.23922975'
	assert decimals(205.473023698, 5) == '205.47302'
	assert decimals(250.0, 5) == '250'
	assert dwsim_version('DWSIM version 9.0.5.0 (28/10/2025 10:42:38)') == '9.0.5.0'
}

fn test_the_committed_report_covers_every_case() {
	// The report is regenerated by hand, so this checks the committed one:
	// a row for every case of the fixture in each of its three tables, and
	// reflux's timings from an optimised build.
	fx := load()!
	text := os.read_file(report_path)!
	assert text.contains('built with gcc') && text.contains(' -prod;'), 'not timed with gcc -prod'
	for c in fx.cases {
		row := '| ${label(c.kind)} | ${mixture(fx.systems[c.system])} | '
		assert text.count(row) == 3, 'case ${c.kind} of ${fx.systems[c.system].name}'
	}
}
