module benchmarks

import math
import strings

// label names a kind of flash.
fn label(kind string) string {
	return match kind {
		'pt2' { 'PT, two phases' }
		'pt1' { 'PT, one phase' }
		'ph' { 'PH' }
		else { 'bubble point at P' }
	}
}

// round_sig rounds x to s significant figures, half away from zero, so
// that the report prints the same under every C compiler (see
// docs/v-for-go.md, §14).
fn round_sig(x f64, s int) f64 {
	if x == 0.0 || !math.is_finite(x) {
		return x
	}
	d := s - 1 - int(math.floor(math.log10(math.abs(x))))
	scale := math.pow(10.0, f64(d))
	return math.round(x * scale) / scale
}

// sig prints x to s significant figures, trailing zeros included: 40.0 and
// 2.00 to three, 999 rather than 999.0. x is rounded first, so the format
// never meets a tie. It's for |x| ≥ 0.001; from 10^s up it prints an integer.
fn sig(x f64, s int) string {
	r := round_sig(x, s)
	if r == 0.0 {
		return '0'
	}
	places := s - 1 - int(math.floor(math.log10(math.abs(r))))
	if places <= 0 {
		return '${i64(r)}'
	}
	return match places {
		1 { '${r:.1f}' }
		2 { '${r:.2f}' }
		3 { '${r:.3f}' }
		else { '${r}' }
	}
}

// duration prints microseconds as µs below a millisecond and ms above, to
// three significant figures.
fn duration(us f64) string {
	return if round_sig(us, 3) < 1000.0 { '${sig(us, 3)} µs' } else { '${sig(us / 1e3, 3)} ms' }
}

// cell is a timing's median, or why there's none.
fn cell(t Timing) string {
	return if t.error != '' { 'failed' } else { duration(t.median_us) }
}

// ratio is how many times slower other is than reflux.
fn ratio(other Timing, reflux Timing) string {
	if other.error != '' || reflux.median_us <= 0.0 {
		return '–'
	}
	return '${sig(other.median_us / reflux.median_us, 2)}×'
}

// deviation is other's answer minus reflux's, in β or K.
fn deviation(kind string, other Timing, reflux Timing) string {
	if other.error != '' {
		return '–'
	}
	d := if kind in ['pt2', 'pt1'] {
		other.answer.beta - reflux.answer.beta
	} else {
		other.answer.t - reflux.answer.t
	}
	return if math.abs(d) < 5e-13 { '0' } else { '${round_sig(d, 2)}' }
}

// decimals prints x to d decimal places, without trailing zeros: 0.25 and
// 1, not 0.25000000 and 1.00000000. It rounds first, so the format never
// meets a tie.
fn decimals(x f64, d int) string {
	scale := math.pow(10.0, f64(d))
	r := math.round(x * scale) / scale
	text := match d {
		5 { '${r:.5f}' }
		8 { '${r:.8f}' }
		else { '${r}' }
	}
	return if text.contains('.') { text.trim_right('0').trim_right('.') } else { text }
}

// dwsim_version is the version number in DWSIM's version string, "DWSIM
// version 9.0.5.0 (date)".
fn dwsim_version(s string) string {
	return if s.contains('version ') { s.all_after('version ').all_before(' ') } else { s }
}

fn mixture(s System) string {
	return '${s.components.len}: ${s.name}'
}

// report is docs/benchmarks.md, from the fixture.
pub fn report(fx Fixture) string {
	mut b := strings.new_builder(4096)
	b.writeln('# Benchmarks')
	b.writeln('')
	b.writeln("Generated by `v run tools/benchmarks.vsh` from `testdata/m3_bench.json`, which `tools/gen_m3_bench.py` writes: M3 step 10, decision D10, exit criterion 8. Don't edit this file by hand.")
	b.writeln('')
	b.writeln('**What is timed.**')
	b.writeln("- **The flashes:** PT with two phases and with one, PH, and the bubble point at a given P, for a 2-, a 5- and a 10-component mixture. All three programs use Peng–Robinson with DWSIM's constants and kᵢⱼ.")
	b.writeln('- **The states:** each case is ${fx.states} nearby states, so nothing is merely repeated: PT and PH at T₀ + 0.05 K·k, the bubble point at P₀·(1 + 0.001·k). PH is by state: each program computes its own H at the PT state, untimed, and its PH flash from that H is timed.')
	b.writeln('- **The timing:** every flash on its own, after one untimed pass over the states, warm, in one process per program. The tables give the median.')
	b.writeln("- **Case by case:** on this laptop the same flash's median moves by up to 3× from one session to another, with its power state, so the three programs time each case one straight after the other, within seconds. Timed minutes apart, the ratios moved by 2×.")
	b.writeln('- **The programs:**')
	b.writeln('  - reflux at its default tolerances (|ln fᵢⱽ − ln fᵢᴸ| ≤ 1e-12, every split verified), built with ${fx.reflux_build.compiler};')
	b.writeln("  - thermo ${fx.source.thermo}'s FlashVL at its default tolerances, from Python ${fx.source.python};")
	b.writeln('  - DWSIM ${dwsim_version(fx.source.dwsim)}\'s "Peng-Robinson (PR)" package, called directly through pythonnet ${fx.source.pythonnet}, at its default PT and PH tolerances and at 1e-8.')
	b.writeln('')
	b.writeln('**The machine:** ${fx.machine.cpu}, ${fx.machine.os}, on ${fx.source.generated}, with V ${fx.reflux_build.v}.')
	b.writeln('')
	b.writeln('## Median time per flash')
	b.writeln('')
	b.writeln('| Flash | Mixture | reflux | thermo | DWSIM | DWSIM at 1e-8 | thermo ÷ reflux | DWSIM ÷ reflux |')
	b.writeln('|---|---|---|---|---|---|---|---|')
	for kind in kinds {
		for c in fx.cases {
			if c.kind != kind {
				continue
			}
			s := fx.systems[c.system]
			r := c.reflux
			b.writeln('| ${label(kind)} | ${mixture(s)} | ${cell(r)} | ${cell(c.thermo)} | ${cell(c.dwsim_default)} | ${cell(c.dwsim_tight)} | ${ratio(c.thermo, r)} | ${ratio(c.dwsim_default, r)} |')
		}
	}
	b.writeln('')
	b.writeln('## The same flashes')
	b.writeln('')
	b.writeln("Each program's answer at a case's first state, minus reflux's: β for PT, and T in K for PH and the bubble point. A PH answer is where each program lands from its own H, so it shows how closely each comes back to its own state.")
	b.writeln('')
	b.writeln('| Flash | Mixture | reflux | thermo | DWSIM | DWSIM at 1e-8 |')
	b.writeln('|---|---|---|---|---|---|')
	for kind in kinds {
		for c in fx.cases {
			if c.kind != kind {
				continue
			}
			s := fx.systems[c.system]
			r := c.reflux
			own := if kind in ['pt2', 'pt1'] {
				'β = ${decimals(r.answer.beta, 8)}'
			} else {
				'${decimals(r.answer.t, 5)} K'
			}
			b.writeln('| ${label(kind)} | ${mixture(s)} | ${own} | ${deviation(kind, c.thermo, r)} | ${deviation(kind, c.dwsim_default, r)} | ${deviation(kind, c.dwsim_tight, r)} |')
		}
	}
	failures := fx.cases.filter(it.thermo.error != '' || it.dwsim_default.error != ''
		|| it.dwsim_tight.error != '')
	if failures.len > 0 {
		b.writeln('')
		b.writeln('## Failures')
		b.writeln('')
		for c in failures {
			s := fx.systems[c.system]
			for name, t in {
				'thermo':        c.thermo
				'DWSIM':         c.dwsim_default
				'DWSIM at 1e-8': c.dwsim_tight
			} {
				if t.error != '' {
					b.writeln('- ${label(c.kind)}, ${mixture(s)}, ${name}: ${t.error}')
				}
			}
		}
	}
	b.writeln('')
	b.writeln('## Fastest flash')
	b.writeln('')
	b.writeln("The minimum over all the timed flashes of each case: what a flash costs when nothing else gets in its way. It's steadier than the median from one run to the next, so its ratios are the better guide.")
	b.writeln('')
	b.writeln('| Flash | Mixture | reflux | thermo | DWSIM | DWSIM at 1e-8 | thermo ÷ reflux | DWSIM ÷ reflux |')
	b.writeln('|---|---|---|---|---|---|---|---|')
	for kind in kinds {
		for c in fx.cases {
			if c.kind != kind {
				continue
			}
			s := fx.systems[c.system]
			b.writeln('| ${label(kind)} | ${mixture(s)} | ${min_cell(c.reflux)} | ${min_cell(c.thermo)} | ${min_cell(c.dwsim_default)} | ${min_cell(c.dwsim_tight)} | ${min_ratio(c.thermo, c.reflux)} | ${min_ratio(c.dwsim_default, c.reflux)} |')
		}
	}
	return b.str()
}

// min_ratio is how many times slower other's fastest flash is than
// reflux's.
fn min_ratio(other Timing, reflux Timing) string {
	if other.error != '' || reflux.min_us <= 0.0 {
		return '–'
	}
	return '${sig(other.min_us / reflux.min_us, 2)}×'
}

fn min_cell(t Timing) string {
	return if t.error != '' { 'failed' } else { duration(t.min_us) }
}
