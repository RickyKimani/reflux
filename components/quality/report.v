module quality

import json2
import math
import os
import components
import components.chemsep

// The CoolProp fixture's shape (testdata/m2_coolprop.json), for its outliers.
struct CoolRef {
	coolprop  f64
	deviation f64
}

struct CoolPoint {
	t         f64
	coolprop  f64
	deviation f64
}

struct CoolCurve {
	key    string
	points []CoolPoint
}

struct CoolFluid {
	coolprop  string
	cas       string
	name      string
	constants map[string]CoolRef
	cp0       CoolCurve
	psat      CoolCurve
}

struct CoolFixture {
	fluids []CoolFluid
}

fn read_coolprop(path string) !CoolFixture {
	return json2.decode[CoolFixture](os.read_file(path)!)!
}

// Deviations from CoolProp beyond these are listed: relative, except ω's.
const outlier = {
	'tc':    0.05
	'pc':    0.05
	'omega': 0.05
	'mw':    1e-4
	'cp0':   0.05
	'psat':  0.05
}

fn render(s Sweep, imp chemsep.Import, cool CoolFixture, banks []components.KijBank, mc components.McBank, db components.Database) string {
	mut o := []string{}
	o << '# Data quality'
	o << ''
	o << "Generated by `v run tools/data_quality.vsh`. Don't edit it: a test fails when"
	o << 'the committed copy differs from a fresh run, so every change shows in a diff.'
	o << ''
	o << 'It covers the ${s.compounds} compounds in `data/components/` (ChemSep 8.50,'
	o << 'converted), the vendored kᵢⱼ and Mathias–Copeman files, and the comparison'
	o << 'with CoolProp in `testdata/m2_coolprop.json`. Nothing here is fixed:'
	o << "these are the data's own defects. Those the importer repaired, and"
	o << 'everything it noticed record by record, are in'
	o << '[data/components/CHANGES.md](../data/components/CHANGES.md).'
	o << ''
	o << '## Summary'
	o << ''
	o << '| Check | Checked | Problems |'
	o << '|---|---|---|'
	o << '| Correlations finite, and positive where they must be | ${s.evaluated} correlations | ${s.properties.len} |'
	o << '| Vapour pressure within 2% of 1 atm at the normal boiling point | ${s.boiling_checked} compounds | ${s.boiling.len} |'
	o << '| Ideal-gas Cp usable | ${s.compounds} compounds | ${s.no_ideal_gas.len} |'
	o << '| Tc, Pc, ω and M present | ${s.compounds} compounds | ${s.no_component.len} |'
	o << '| Own vapour-pressure correlation usable | ${s.compounds} compounds | ${s.fallbacks.len} use Antoine |'
	o << '| InChIKey unique | ${s.compounds} compounds | ${s.shared_inchikey.len} shared |'
	o << '| Eq.-106 ranges within Tc | | ${s.past_tc.len} run past it |'
	o << ''
	o << '## Correlations: finite, and positive where they must be'
	o << ''
	o << 'Each correlation reflux can use, at ${sweep_points} temperatures evenly spaced'
	o << 'over its range (skipping 0 K). Second virial coefficients may have either'
	o << 'sign, and heats of vaporization and surface tensions may reach zero, at Tc.'
	o << ''
	o << '${s.near_tc} of the ${s.properties.len} fail within 1% of Tc: fits that cross zero, or reach a'
	o << 'pole, at the critical point. The rest are worth a closer look.'
	o << ''
	o << problems_table(s.properties)
	o << '## Vapour pressure at the normal boiling point'
	o << ''
	o << 'Psat(Tb) against 101325 Pa, for the ${s.boiling_checked} compounds with a Tb and a'
	o << "usable vapour pressure. Listed when it's off by more than 2%."
	o << ''
	o << '| CAS | Compound | Correlation | Tb (K) | Psat(Tb) (Pa) | Deviation | Tb in range |'
	o << '|---|---|---|---|---|---|---|'
	for b in s.boiling {
		o << '| ${b.cas} | ${md(b.name)} | ${b.key} | ${g5(b.tb)} | ${g4(b.p)} | ${pct(b.deviation)} | ${yes(b.in_range)} |'
	}
	o << ''
	o << "## Peng–Robinson against ChemSep's vapour pressure"
	o << ''
	o << "PR with ChemSep's Tc, Pc and ω and the Soave α, against the compound's"
	o << 'vapour-pressure correlation, as PR/ChemSep − 1. This is M2 exit criterion'
	o << '6. PR with the Soave α is known to be poor for polar compounds such as'
	o << 'water and methanol; Mathias–Copeman α (step 6) is the fix. A * marks a'
	o << "temperature outside the correlation's fitted range. A large deviation"
	o << "can be ChemSep's correlation rather than PR: n-decane's is 37% below"
	o << "CoolProp's at Tr 0.95 (see the CoolProp outliers below), and PR is the"
	o << 'closer of the two there.'
	o << ''
	o << '| CAS | Compound | ' + reduced_temperatures.map('Tr ${it}').join(' | ') + ' |'
	o << '|---|---|' + reduced_temperatures.map('---').join('|') + '|'
	for p in s.pr {
		mut cells := []string{}
		for i, d in p.deviations {
			cells << pct(d) + if p.in_range[i] { '' } else { ' *' }
		}
		o << '| ${p.cas} | ${md(p.name)} | ${cells.join(' | ')} |'
	}
	o << ''
	o << '## Checks across records'
	o << ''
	o << '### Shared InChIKeys (${s.shared_inchikey.len})'
	o << ''
	o << problems_table(s.shared_inchikey)
	o << '### No usable ideal-gas Cp (${s.no_ideal_gas.len})'
	o << ''
	o << problems_table(s.no_ideal_gas)
	o << '### No Tc, Pc, ω or M (${s.no_component.len})'
	o << ''
	o << problems_table(s.no_component)
	o << '### Vapour pressure from the Antoine record (${s.fallbacks.len})'
	o << ''
	o << "ChemSep's eq. 200 looks like a Wagner equation, with Pc as its fifth"
	o << 'coefficient and Tmax at Tc. Supporting it would give the eq.-200 compounds'
	o << 'their own fits back.'
	o << ''
	o << problems_table(s.fallbacks)
	o << '### Eq.-106 ranges that run past Tc (${s.past_tc.len})'
	o << ''
	o << 'Eq. 106 is 0 at and above Tc, so these are harmless for heats of'
	o << 'vaporization and surface tensions.'
	o << ''
	o << problems_table(s.past_tc)
	o << '## ChemSep against CoolProp: the outliers'
	o << ''
	o << 'From the ${cool.fluids.len} fluids both have. Listed when ChemSep is off by'
	o << 'more than 5% (0.05 absolute in ω; 1e-4 in M); a curve shows its worst'
	o << "point. CoolProp's own equations are less certain for some of these"
	o << 'fluids, such as the siloxanes and the methyl esters. Most vapour-pressure'
	o << 'outliers sit near the triple point, where the pressure is tiny and a small'
	o << 'absolute error is a large relative one.'
	o << ''
	o << '| Fluid | CAS | Quantity | ChemSep − CoolProp | Where |'
	o << '|---|---|---|---|---|'
	for f in cool.fluids {
		for key in ['tc', 'pc', 'omega', 'mw'] {
			ref := f.constants[key] or { continue }
			if math.abs(ref.deviation) > outlier[key] {
				dev := if key == 'omega' { signed(f3(ref.deviation)) } else { pct(ref.deviation) }
				o << '| ${f.coolprop} | ${f.cas} | ${key} | ${dev} | ChemSep ${key_value(f, key)} |'
			}
		}
		for key, curve in {
			'cp0':  f.cp0
			'psat': f.psat
		} {
			if curve.points.len == 0 {
				continue
			}
			mut worst := curve.points[0]
			for p in curve.points {
				if math.abs(p.deviation) > math.abs(worst.deviation) {
					worst = p
				}
			}
			if math.abs(worst.deviation) > outlier[key] {
				o << '| ${f.coolprop} | ${f.cas} | ${key} | ${pct(worst.deviation)} | at ${g4(worst.t)} K |'
			}
		}
	}
	o << ''
	o << '## Parameter files'
	o << ''
	o << '| File | Entries | Pairs or compounds | Listed more than once | Unreadable lines | CAS numbers not in the database |'
	o << '|---|---|---|---|---|---|'
	known := db.list().map(it.cas)
	for b in banks {
		mut pairs := map[string]int{}
		mut unknown := map[string]bool{}
		for e in b.entries {
			key := if e.cas1 < e.cas2 { '${e.cas1}/${e.cas2}' } else { '${e.cas2}/${e.cas1}' }
			pairs[key]++
			for cas in [e.cas1, e.cas2] {
				if cas !in known {
					unknown[cas] = true
				}
			}
		}
		mut u := unknown.keys()
		u.sort()
		o << '| `${b.file}` | ${b.entries.len} | ${pairs.len} pairs | ${pairs.values().filter(it > 1).len} | ${b.defects.len} | ${u.join(', ')} |'
	}
	mut seen := map[string]int{}
	mut unknown_mc := []string{}
	for e in mc.entries {
		seen[e.cas]++
		if e.cas !in known && e.cas !in unknown_mc {
			unknown_mc << e.cas
		}
	}
	o << '| `${mc.file}` | ${mc.entries.len} | ${seen.len} compounds | ${seen.values().filter(it > 1).len} | ${mc.defects.len} | ${unknown_mc.join(', ')} |'
	o << ''
	o << 'Where a pair or compound is listed more than once, reflux uses the first'
	o << 'listing (M2 decision D12). The unreadable lines:'
	o << ''
	for d in mc.defects {
		o << '- `${mc.file}` line ${d.line}: ${md(d.why)}'
	}
	for b in banks {
		for d in b.defects {
			o << '- `${b.file}` line ${d.line}: ${md(d.why)}'
		}
	}
	o << ''
	o << '## From the import'
	o << ''
	o << 'Counted here; listed compound by compound in'
	o << '[CHANGES.md](../data/components/CHANGES.md).'
	o << ''
	o << '| What | Count |'
	o << '|---|---|'
	o << '| Records read | ${arrays_sum(imp.sources.map(it.records))} |'
	o << '| Duplicates dropped | ${imp.duplicates.len} |'
	o << '| Repairs | ${imp.repairs.len} |'
	for kind, label in {
		chemsep.FindingKind.bad_range: 'Impossible correlation ranges'
		.unsupported_form:             "Correlations in forms reflux can't evaluate"
		.unused_coefficients:          "Correlations with non-zero coefficients their form doesn't use"
		.no_coefficients:              'Correlations with no coefficients'
		.partial_set:                  'Incomplete Mathias–Copeman sets'
		.incomplete:                   'Compounds without Tc, Pc or ω'
	} {
		o << '| ${label} | ${imp.findings.filter(it.kind == kind).len} |'
	}
	return o.join('\n') + '\n'
}

fn problems_table(ps []Problem) string {
	if ps.len == 0 {
		return 'None.\n'
	}
	mut o := ['| CAS | Compound | Problem |', '|---|---|---|']
	for p in ps {
		o << '| ${p.cas} | ${md(p.name)} | ${md(p.what)} |'
	}
	return o.join('\n') + '\n'
}

fn key_value(f CoolFluid, key string) string {
	ref := f.constants[key] or { return '' }
	v := if key == 'omega' {
		ref.coolprop + ref.deviation
	} else {
		ref.coolprop * (1.0 + ref.deviation)
	}
	return '${g4(v)}, CoolProp ${g4(ref.coolprop)}'
}

fn pct(x f64) string {
	return signed(f2(x * 100.0)) + '%'
}

fn yes(b bool) string {
	return if b { 'yes' } else { 'no' }
}

fn md(s string) string {
	return s.replace('|', '\\|')
}

fn arrays_sum(xs []int) int {
	mut t := 0
	for x in xs {
		t += x
	}
	return t
}
