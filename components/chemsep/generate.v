// generate renders everything in data/components/ from an import, as a map
// from file name to contents. Writing these files and comparing them with
// the committed ones are the same operation, so the test that checks the
// directory is up to date (M2 exit criterion 2) runs exactly this.
pub fn generate(imp Import) !map[string]string {
	mut files := map[string]string{}
	for r in imp.records {
		header := "# ${r.name} (${r.ids.cas}), from the ChemSep database.\n# Generated by tools/import_chemsep.vsh: don't edit. See README.md.\n"
		files['${r.ids.cas}.toml'] = header + components.write_toml(r) or {
			return error('${r.ids.cas}: ${err}')
		}
	}
	entries := imp.records.map(components.IndexEntry.of(it))
	files['index.toml'] = "# Every compound in this directory, for lookup without parsing each file.\n# Generated by tools/import_chemsep.vsh: don't edit.\n" +
		components.write_index(entries)!
	files['README.md'] = readme
	files['CHANGES.md'] = imp.changes()
	return files
}

const readme = "# Component data

One TOML file per compound, named by its CAS number, in reflux's component
format ([docs/data-format.md](../../docs/data-format.md)). `index.toml` lists
them all, so lookup by name doesn't have to parse every file.

**Everything here is generated. Don't edit it.**
[tools/import_chemsep.vsh](../../tools/import_chemsep.vsh) writes this whole
directory from the ChemSep XML in [data/vendor/chemsep/](../vendor/chemsep/),
and a test fails if it's out of date. To change a compound, fix the importer,
or add your own component file in a directory of your own.

