[NOTICE](../vendor/chemsep/NOTICE.md).

How these files differ from it is documented in [CHANGES.md](CHANGES.md).
"

// changes renders CHANGES.md: how the generated files differ from the
// Standard Version (the repairs and dropped duplicates), and what the import
// noticed but left alone. It's also the import report of M2 exit criterion 1.
pub fn (imp Import) changes() string {
	mut s := []string{}
	s << '# Changes from the ChemSep Standard Version'
	s << ''
	s << 'Generated by tools/import_chemsep.vsh from:'
	s << ''
	s << '| File | Library | Records |'
	s << '|---|---|---|'
	for src in imp.sources {
		s << '| `${src.path}` | ${md(src.library)} | ${src.records} |'
	}
	total := arrays_sum(imp.sources.map(it.records))
	s << ''
	s << '${total} records became ${imp.records.len} compound files.'
	s << ''
	s << '## Throughout'
	s << ''
	s << "- The XML is converted to reflux's TOML format, one file per compound
  ([docs/data-format.md](../../docs/data-format.md)). ChemSep's element
  names become reflux keys by the table in
  [components/chemsep/fields.v](../../components/chemsep/fields.v).
- Scalars are converted to SI per mol: values per kmol are divided by 1000,
  exactly, by moving the decimal point. Other scalars are unchanged.
- Correlation coefficients, units and temperature ranges are unchanged.
- Numbers are printed in shortest round-trip form, for instance `3.796E+06`
  as `3.796e+06`. The values are identical."
	s << ''
	s << '## Repairs (${imp.repairs.len})'
	s << ''
	s << '| CAS | Compound | Key | Before | After |'
	s << '|---|---|---|---|---|'
	for r in imp.repairs {
		s << '| ${r.cas} | ${md(r.name)} | `${r.key}` | `${md(r.before)}` | `${md(r.after)}` |'
	}
	s << ''
	s << '## Duplicates dropped (${imp.duplicates.len})'
	s << ''
	s << 'The first occurrence of a CAS number is kept.'
	s << ''
	s << "Where the kept copy's element is wrong and the dropped one's right, it is"
	s << 'taken from the dropped copy: see `take_from_duplicate` in'
	s << '[components/chemsep/chemsep.v](../../components/chemsep/chemsep.v), and the'
	s << 'repairs above.'
	s << ''
	s << '| CAS | Compound | Kept | Dropped | Elements that differ | Taken from the dropped copy |'
	s << '|---|---|---|---|---|---|'
	for d in imp.duplicates {
		s << '| ${d.cas} | ${md(d.name)} | ${d.kept} | ${d.dropped} | ${d.differing.join(', ')} | ${d.taken.join(', ')} |'
	}
	s << ''
	s << '## Noted, not changed'
	s << ''
	s << 'These values are kept exactly as ChemSep has them.'
	headings := {
		FindingKind.bad_range: 'Impossible correlation ranges'
		.unsupported_form:     "Equation forms reflux can't evaluate"
		.unused_coefficients:  "Coefficients the equation form doesn't use"
		.no_coefficients:      'Correlations with no coefficients'
		.partial_set:          'Incomplete Mathias–Copeman sets'
		.incomplete:           'Compounds without Tc, Pc or ω'
	}
	for kind, heading in headings {
		found := imp.findings.filter(it.kind == kind)
		s << ''
		s << '### ${heading} (${found.len})'
		s << ''
		s << '| CAS | Compound | Detail |'
		s << '|---|---|---|'
		for f in found {
			s << '| ${f.cas} | ${md(f.name)} | ${md(f.what)} |'
		}
	}
	return s.join('\n') + '\n'
}

// md escapes the one character that breaks a Markdown table cell.
fn md(s string) string {
	return s.replace('|', '\\|')
}

fn arrays_sum(xs []int) int {
	mut t := 0
	for x in xs {
		t += x
	}
	return t
}
